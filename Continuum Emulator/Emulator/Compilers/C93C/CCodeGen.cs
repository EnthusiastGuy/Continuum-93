using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;

namespace Continuum93.Emulator.Compilers.C93C
{
    /// <summary>
    /// Generates Continuum 93 assembly from the typed AST.
    ///
    /// Register conventions:
    ///   ABCD  accumulator (every expression leaves its value here; pointers use the low 24 bits, BCD)
    ///   EFGH  second operand
    ///   IJKL  division remainder / scratch
    ///   MNO   memory address for loads and stores
    ///   QRS   frame pointer: parameters at (QRS + 4*i), locals at negative offsets
    ///   T     shift count
    ///   UVW   C stack pointer (grows down from StackTop); arguments are pushed right to left
    ///   XYZ   scratch address
    /// Expression temporaries use the hardware register stack (PUSH/POP); calls use CALL/RET.
    /// Notes on the ISA: plain ADD/SUB/MUL take 8-bit immediates, so the 32/24-bit forms (ADD32, SUB24, ...)
    /// are used for immediates and MUL/DIV always take a register operand.
    /// </summary>
    public sealed class CCodeGen
    {
        public const uint CodeOrigin = 0x080000;
        public const uint StackTop = 0xE00000;
        public const string StartLabel = ".c__start";
        public const string HeapStartLabel = ".c___heap_start";

        private readonly StringBuilder _sb = new();
        private readonly List<CCompileError> _errors;
        private int _labelCounter;
        private CFunction _fn;

        public CCodeGen(List<CCompileError> errors, int labelCounterStart)
        {
            _errors = errors;
            _labelCounter = labelCounterStart;
        }

        public string Generate(CTranslationUnit unit, uint origin = CodeOrigin, uint stackTop = StackTop)
        {
            Dictionary<string, CFunction> functions = unit.Functions.ToDictionary(f => f.Symbol.Label);
            HashSet<string> reachable = ComputeReachable(unit, functions);

            Line($"; Generated by the Continuum 93 C compiler");
            Line($"#ORG 0x{origin:X6}");
            Label(StartLabel);
            Emit($"LD UVW, 0x{stackTop:X6}");

            // Patch address constants into initialized globals
            foreach (CSymbol g in unit.Globals.Where(g => g.IsDefined))
            {
                foreach (CRelocation r in g.Relocations)
                {
                    Emit($"LD ABCD, {r.TargetLabel}");
                    AddImm32("ABCD", r.Addend);
                    Emit($"LD MNO, {g.Label}");
                    if (r.Offset != 0) Emit($"ADD24 MNO, {r.Offset}");
                    Emit("LD (MNO), ABCD");
                }
            }

            // main(argc = 0, argv = 0)
            Emit("SUB24 UVW, 8");
            Emit("LD ABCD, 0");
            Emit("LD (UVW), ABCD");
            Emit("LD (UVW + 4), ABCD");
            Emit("CALL .c_main");
            Emit("ADD24 UVW, 8");
            Emit("RET");

            foreach (CFunction fn in unit.Functions)
            {
                if (reachable.Contains(fn.Symbol.Label))
                    GenFunction(fn);
            }

            Line("");
            Line("; ---------------------------------------------------------- data");
            foreach (var (label, bytes) in unit.Strings)
            {
                Label(label);
                EmitBytes(bytes);
            }

            foreach (CSymbol g in unit.Globals)
            {
                if (!g.IsDefined)
                    continue;
                Label(g.Label);
                byte[] data = g.InitData ?? new byte[g.Type.Size];
                if (data.Length < g.Type.Size)
                    Array.Resize(ref data, g.Type.Size);
                EmitBytes(data.Length == 0 ? [0] : data);
            }

            Label(HeapStartLabel);
            Emit("#DB 0");
            return _sb.ToString();
        }

        private static HashSet<string> ComputeReachable(CTranslationUnit unit, Dictionary<string, CFunction> functions)
        {
            var reachable = new HashSet<string>();
            var work = new Stack<string>();
            work.Push(".c_main");

            // Anything referenced from global initializers or inline asm stays alive
            foreach (CSymbol g in unit.Globals)
                foreach (CRelocation r in g.Relocations)
                    work.Push(r.TargetLabel);
            foreach (CFunction f in unit.Functions)
                foreach (string l in AsmReferences(f.Body))
                    f.CalledFunctions.Add(l);

            while (work.Count > 0)
            {
                string l = work.Pop();
                if (!reachable.Add(l))
                    continue;
                if (functions.TryGetValue(l, out CFunction f))
                    foreach (string c in f.CalledFunctions)
                        work.Push(c);
            }
            return reachable;
        }

        private static IEnumerable<string> AsmReferences(CNode node)
        {
            if (node == null) yield break;
            if (node.Kind == CNodeKind.Asm)
            {
                foreach (System.Text.RegularExpressions.Match m in System.Text.RegularExpressions.Regex.Matches(node.AsmText, @"\.c_[A-Za-z0-9_]+"))
                    yield return m.Value;
            }
            foreach (CNode child in new[] { node.Then, node.Els, node.Init, node.BodyStmt })
                foreach (string s in AsmReferences(child))
                    yield return s;
            if (node.Body != null)
                foreach (CNode child in node.Body)
                    foreach (string s in AsmReferences(child))
                        yield return s;
        }

        // ====================================================================== Functions

        private void GenFunction(CFunction fn)
        {
            _fn = fn;
            Line("");
            Line($"; {fn.Type.Base} {fn.Name}(...)");
            Label(fn.Symbol.Label);
            Emit("PUSH QRS");
            Emit("LD QRS, UVW");
            if (fn.FrameSize > 0)
                Emit($"SUB24 UVW, {fn.FrameSize}");

            GenStmt(fn.Body);

            if (fn.Name == "main")
                Emit("LD ABCD, 0");     // Falling off the end of main returns 0

            Label(fn.ReturnLabel);
            Emit("LD UVW, QRS");
            Emit("POP QRS");
            Emit("RET");
            _fn = null;
        }

        // ====================================================================== Statements

        private void GenStmt(CNode node)
        {
            switch (node.Kind)
            {
                case CNodeKind.Block:
                    foreach (CNode s in node.Body)
                        GenStmt(s);
                    return;

                case CNodeKind.ExprStmt:
                    GenExpr(node.Lhs);
                    return;

                case CNodeKind.Empty:
                    return;

                case CNodeKind.Return:
                    if (node.Lhs != null)
                        GenExpr(node.Lhs);
                    Emit($"JP {_fn.ReturnLabel}");
                    return;

                case CNodeKind.If:
                    {
                        string elseLabel = NewLabel(), endLabel = NewLabel();
                        GenBranch(node.Cond, node.Els != null ? elseLabel : endLabel, false);
                        GenStmt(node.Then);
                        if (node.Els != null)
                        {
                            Emit($"JP {endLabel}");
                            Label(elseLabel);
                            GenStmt(node.Els);
                        }
                        Label(endLabel);
                        return;
                    }

                case CNodeKind.For:
                    {
                        string begin = NewLabel();
                        if (node.Init != null)
                            GenStmt(node.Init);
                        Label(begin);
                        if (node.Cond != null)
                            GenBranch(node.Cond, node.BreakLabel, false);
                        GenStmt(node.Then);
                        Label(node.ContinueLabel);
                        if (node.Inc != null)
                            GenExpr(node.Inc);
                        Emit($"JP {begin}");
                        Label(node.BreakLabel);
                        return;
                    }

                case CNodeKind.Do:
                    {
                        string begin = NewLabel();
                        Label(begin);
                        GenStmt(node.Then);
                        Label(node.ContinueLabel);
                        GenBranch(node.Cond, begin, true);
                        Label(node.BreakLabel);
                        return;
                    }

                case CNodeKind.Switch:
                    GenExpr(node.Cond);
                    foreach (CNode c in node.Cases)
                    {
                        Emit($"CP ABCD, {Imm(c.CaseValue)}");
                        Emit($"JP EQ, {c.UniqueLabel}");
                    }
                    Emit($"JP {(node.DefaultCase != null ? node.DefaultCase.UniqueLabel : node.BreakLabel)}");
                    GenStmt(node.Then);
                    Label(node.BreakLabel);
                    return;

                case CNodeKind.Case:
                    Label(node.UniqueLabel);
                    GenStmt(node.BodyStmt);
                    return;

                case CNodeKind.Goto:
                    Emit($"JP {node.UniqueLabel}");
                    return;

                case CNodeKind.Label:
                    Label(node.UniqueLabel);
                    GenStmt(node.BodyStmt);
                    return;

                case CNodeKind.Asm:
                    foreach (string l in node.AsmText.Replace("\r", "").Split('\n'))
                        if (l.Trim().Length > 0)
                            Emit(l.Trim());
                    return;
            }

            throw Internal(node, $"Unexpected statement kind {node.Kind}");
        }

        // ====================================================================== Conditions

        private static readonly Dictionary<CNodeKind, (string Cond, string Inverse)> CompareConds = new()
        {
            [CNodeKind.Eq] = ("EQ", "NE"),
            [CNodeKind.Ne] = ("NE", "EQ"),
            [CNodeKind.Lt] = ("LT", "GTE"),
            [CNodeKind.Le] = ("LTE", "GT"),
        };

        /// <summary>Jumps to <paramref name="label"/> when the condition's truth equals <paramref name="jumpIfTrue"/>.</summary>
        private void GenBranch(CNode cond, string label, bool jumpIfTrue)
        {
            switch (cond.Kind)
            {
                case CNodeKind.Num:
                    if ((cond.Value != 0) == jumpIfTrue)
                        Emit($"JP {label}");
                    return;

                case CNodeKind.Eq:
                case CNodeKind.Ne:
                case CNodeKind.Lt:
                case CNodeKind.Le:
                    {
                        GenCompare(cond);
                        var (c, inv) = CompareConds[cond.Kind];
                        Emit($"JP {(jumpIfTrue ? c : inv)}, {label}");
                        return;
                    }

                case CNodeKind.LogNot:
                    GenBranch(cond.Lhs, label, !jumpIfTrue);
                    return;

                case CNodeKind.LogAnd:
                    if (jumpIfTrue)
                    {
                        string skip = NewLabel();
                        GenBranch(cond.Lhs, skip, false);
                        GenBranch(cond.Rhs, label, true);
                        Label(skip);
                    }
                    else
                    {
                        GenBranch(cond.Lhs, label, false);
                        GenBranch(cond.Rhs, label, false);
                    }
                    return;

                case CNodeKind.LogOr:
                    if (jumpIfTrue)
                    {
                        GenBranch(cond.Lhs, label, true);
                        GenBranch(cond.Rhs, label, true);
                    }
                    else
                    {
                        string skip = NewLabel();
                        GenBranch(cond.Lhs, skip, true);
                        GenBranch(cond.Rhs, label, false);
                        Label(skip);
                    }
                    return;
            }

            GenExpr(cond);
            Emit("CP ABCD, 0");
            Emit($"JP {(jumpIfTrue ? "NZ" : "Z")}, {label}");
        }

        /// <summary>Compares lhs (ABCD) with rhs and leaves the flags set.</summary>
        private void GenCompare(CNode node)
        {
            string op = node.Lhs.Type.Decay().Unsigned ? "CP" : "SCP";
            string rhs = GenOperands(node.Lhs, node.Rhs, allowImmediate: true);
            Emit($"{op} ABCD, {rhs}");
        }

        // ====================================================================== Expressions

        /// <summary>
        /// Evaluates lhs into ABCD and rhs into EFGH (or returns an immediate operand string for constants).
        /// </summary>
        private string GenOperands(CNode lhs, CNode rhs, bool allowImmediate)
        {
            if (allowImmediate && rhs.Kind == CNodeKind.Num)
            {
                GenExpr(lhs);
                return Imm(rhs.Value);
            }

            if (IsLeaf(lhs))
            {
                // A leaf only touches ABCD/MNO, so rhs can be parked in EFGH
                GenExpr(rhs);
                Emit("LD EFGH, ABCD");
                GenExpr(lhs);
                return "EFGH";
            }

            GenExpr(rhs);
            Emit("PUSH ABCD");
            GenExpr(lhs);
            Emit("POP EFGH");
            return "EFGH";
        }

        /// <summary>Expressions whose code only uses ABCD and MNO (no calls, no temporaries).</summary>
        private static bool IsLeaf(CNode n) =>
            n.Kind switch
            {
                CNodeKind.Num => true,
                CNodeKind.StrLabel => true,
                CNodeKind.Var => true,
                CNodeKind.Addr => n.Lhs.Kind == CNodeKind.Var,
                CNodeKind.Cast => IsLeaf(n.Lhs),
                CNodeKind.Deref => n.Lhs.Kind == CNodeKind.Var,
                _ => false
            };

        private void GenExpr(CNode node)
        {
            switch (node.Kind)
            {
                case CNodeKind.Num:
                    Emit($"LD ABCD, {Imm(node.Value)}");
                    return;

                case CNodeKind.StrLabel:
                    Emit($"LD ABCD, {node.Label}");
                    return;

                case CNodeKind.Var:
                    if (TryLoadVarDirect(node.Var, node.Type))
                        return;
                    GenAddr(node);
                    Load(node.Type);
                    return;

                case CNodeKind.Member:
                case CNodeKind.Deref:
                    GenAddr(node);
                    Load(node.Type);
                    return;

                case CNodeKind.Addr:
                    GenAddr(node.Lhs);
                    return;

                case CNodeKind.Assign:
                    GenAssign(node);
                    return;

                case CNodeKind.Cast:
                    GenExpr(node.Lhs);
                    Convert(node.Lhs.Type.Decay(), node.Type);
                    return;

                case CNodeKind.Neg:
                    GenExpr(node.Lhs);
                    Emit("INV ABCD");
                    Emit("INC ABCD");
                    return;

                case CNodeKind.BitNot:
                    GenExpr(node.Lhs);
                    Emit("INV ABCD");
                    return;

                case CNodeKind.LogNot:
                    {
                        string done = NewLabel();
                        GenExpr(node.Lhs);
                        Emit("CP ABCD, 0");
                        Emit("LD ABCD, 1");
                        Emit($"JP Z, {done}");
                        Emit("LD ABCD, 0");
                        Label(done);
                        return;
                    }

                case CNodeKind.LogAnd:
                case CNodeKind.LogOr:
                    {
                        string falseLabel = NewLabel(), done = NewLabel();
                        GenBranch(node, falseLabel, false);
                        Emit("LD ABCD, 1");
                        Emit($"JP {done}");
                        Label(falseLabel);
                        Emit("LD ABCD, 0");
                        Label(done);
                        return;
                    }

                case CNodeKind.Eq:
                case CNodeKind.Ne:
                case CNodeKind.Lt:
                case CNodeKind.Le:
                    {
                        string done = NewLabel();
                        GenCompare(node);
                        Emit("LD ABCD, 1");                 // LD does not alter flags
                        Emit($"JP {CompareConds[node.Kind].Cond}, {done}");
                        Emit("LD ABCD, 0");
                        Label(done);
                        return;
                    }

                case CNodeKind.Cond:
                    {
                        string elseLabel = NewLabel(), done = NewLabel();
                        GenBranch(node.Cond, elseLabel, false);
                        GenExpr(node.Then);
                        Emit($"JP {done}");
                        Label(elseLabel);
                        GenExpr(node.Els);
                        Label(done);
                        return;
                    }

                case CNodeKind.Comma:
                    GenExpr(node.Lhs);
                    GenExpr(node.Rhs);
                    return;

                case CNodeKind.Call:
                    GenCall(node);
                    return;

                case CNodeKind.MemZero:
                    if (node.Var.Type.Size > 0)
                    {
                        GenAddr(new CNode(CNodeKind.Var, node.Tok) { Var = node.Var, Type = node.Var.Type });
                        Emit("LD MNO, BCD");
                        Emit($"MEMF MNO, {node.Var.Type.Size}, 0");
                    }
                    return;

                case CNodeKind.Add:
                case CNodeKind.Sub:
                    {
                        if (node.Rhs.Kind == CNodeKind.Num)
                        {
                            GenExpr(node.Lhs);
                            long v = node.Kind == CNodeKind.Add ? node.Rhs.Value : -node.Rhs.Value;
                            AddImm32("ABCD", v);
                            return;
                        }
                        string rhs = GenOperands(node.Lhs, node.Rhs, false);
                        Emit($"{(node.Kind == CNodeKind.Add ? "ADD" : "SUB")} ABCD, {rhs}");
                        return;
                    }

                case CNodeKind.Mul:
                    {
                        if (node.Rhs.Kind == CNodeKind.Num && IsPowerOfTwo(node.Rhs.Value, out int shift))
                        {
                            GenExpr(node.Lhs);
                            if (shift > 0) Emit($"SL ABCD, {shift}");
                            return;
                        }
                        string rhs = GenOperands(node.Lhs, node.Rhs, false);
                        Emit($"MUL ABCD, {rhs}");
                        return;
                    }

                case CNodeKind.Div:
                case CNodeKind.Mod:
                    {
                        bool unsigned = node.Type.Unsigned;
                        if (unsigned && node.Rhs.Kind == CNodeKind.Num && IsPowerOfTwo(node.Rhs.Value, out int shift))
                        {
                            GenExpr(node.Lhs);
                            if (node.Kind == CNodeKind.Div)
                            {
                                if (shift > 0) Emit($"SR ABCD, {shift}");
                            }
                            else
                            {
                                Emit($"AND ABCD, {Imm(node.Rhs.Value - 1)}");
                            }
                            return;
                        }
                        string rhs = GenOperands(node.Lhs, node.Rhs, false);
                        Emit($"{(unsigned ? "DIV" : "SDIV")} ABCD, {rhs}, IJKL");
                        if (node.Kind == CNodeKind.Mod)
                            Emit("LD ABCD, IJKL");
                        return;
                    }

                case CNodeKind.BitAnd:
                case CNodeKind.BitOr:
                case CNodeKind.BitXor:
                    {
                        string op = node.Kind switch { CNodeKind.BitAnd => "AND", CNodeKind.BitOr => "OR", _ => "XOR" };
                        string rhs = GenOperands(node.Lhs, node.Rhs, true);
                        Emit($"{op} ABCD, {rhs}");
                        return;
                    }

                case CNodeKind.Shl:
                case CNodeKind.Shr:
                    GenShift(node);
                    return;
            }

            throw Internal(node, $"Unexpected expression kind {node.Kind}");
        }

        private void GenShift(CNode node)
        {
            bool left = node.Kind == CNodeKind.Shl;
            bool arithmetic = !left && !node.Type.Unsigned;
            string amount;

            if (node.Rhs.Kind == CNodeKind.Num)
            {
                GenExpr(node.Lhs);
                amount = (node.Rhs.Value & 31).ToString();
                if (amount == "0")
                    return;
            }
            else
            {
                GenOperands(node.Lhs, node.Rhs, false);
                Emit("LD T, H");
                amount = "T";
            }

            if (left)
            {
                Emit($"SL ABCD, {amount}");
                return;
            }

            if (!arithmetic)
            {
                Emit($"SR ABCD, {amount}");
                return;
            }

            // Arithmetic shift right: negative values are shifted as ~(~x >> n)
            string positive = NewLabel(), done = NewLabel();
            Emit("SCP ABCD, 0");
            Emit($"JP GTE, {positive}");
            Emit("INV ABCD");
            Emit($"SR ABCD, {amount}");
            Emit("INV ABCD");
            Emit($"JP {done}");
            Label(positive);
            Emit($"SR ABCD, {amount}");
            Label(done);
        }

        private void GenAssign(CNode node)
        {
            CType ty = node.Lhs.Type;

            if (ty.IsStruct)
            {
                // Struct copy: source address in ABCD, destination in MNO
                GenAddr(node.Lhs);
                Emit("PUSH ABCD");
                GenExpr(node.Rhs);
                Emit("POP EFGH");
                Emit("LD MNO, FGH");
                Emit($"MEMC BCD, MNO, {ty.Size}");
                Emit("LD ABCD, 0");
                Emit("LD BCD, MNO");
                return;
            }

            if (node.Lhs.Kind == CNodeKind.Var && DirectOperand(node.Lhs.Var) != null)
            {
                GenExpr(node.Rhs);
                StoreDirect(node.Lhs.Var, ty);
                return;
            }

            if (IsLeafAddress(node.Lhs))
            {
                GenExpr(node.Rhs);
                Emit("LD EFGH, ABCD");
                GenAddr(node.Lhs);
                Emit("LD MNO, BCD");
                Emit("LD ABCD, EFGH");
                Store(ty);
                return;
            }

            GenAddr(node.Lhs);
            Emit("PUSH ABCD");
            GenExpr(node.Rhs);
            Emit("POP EFGH");
            Emit("LD MNO, FGH");
            Store(ty);
        }

        /// <summary>Lvalues whose address computation only touches ABCD.</summary>
        private static bool IsLeafAddress(CNode n) =>
            n.Kind switch
            {
                CNodeKind.Var => true,
                CNodeKind.Deref => n.Lhs.Kind == CNodeKind.Var,
                CNodeKind.Member => IsLeafAddress(n.Lhs),
                _ => false
            };

        private void GenCall(CNode node)
        {
            for (int i = node.Args.Count - 1; i >= 0; i--)
            {
                GenExpr(node.Args[i]);
                Emit("SUB24 UVW, 4");
                Emit("LD (UVW), ABCD");
            }

            if (node.DirectCallee != null)
            {
                Emit($"CALL {node.DirectCallee.Label}");
            }
            else
            {
                GenExpr(node.Lhs);
                Emit("LD MNO, BCD");
                Emit("CALL MNO");
            }

            if (node.Args.Count > 0)
                Emit($"ADD24 UVW, {node.Args.Count * 4}");
        }

        // ====================================================================== Addresses, loads and stores

        private void GenAddr(CNode node)
        {
            switch (node.Kind)
            {
                case CNodeKind.Var:
                    if (node.Var.Kind == CSymbolKind.Local)
                    {
                        Emit("LD ABCD, 0");
                        Emit("LD BCD, QRS");
                        AddImm32("ABCD", node.Var.Offset);
                    }
                    else
                    {
                        Emit($"LD ABCD, {node.Var.Label}");
                    }
                    return;

                case CNodeKind.StrLabel:
                    Emit($"LD ABCD, {node.Label}");
                    return;

                case CNodeKind.Deref:
                    GenExpr(node.Lhs);
                    return;

                case CNodeKind.Member:
                    GenAddr(node.Lhs);
                    AddImm32("ABCD", node.Member.Offset);
                    return;

                case CNodeKind.Comma:
                    GenExpr(node.Lhs);
                    GenAddr(node.Rhs);
                    return;

                case CNodeKind.Cond:
                case CNodeKind.Call:
                case CNodeKind.Assign:
                    // Struct-valued expressions evaluate to their address
                    if (node.Type.IsStruct)
                    {
                        GenExpr(node);
                        return;
                    }
                    break;
            }

            throw Internal(node, "Expression is not an lvalue");
        }

        /// <summary>Operand string for a variable that can be accessed without computing its address.</summary>
        private static string DirectOperand(CSymbol v)
        {
            if (v.Kind == CSymbolKind.Local)
                return v.Offset >= 0 ? $"(QRS + {v.Offset})" : $"(QRS - {-v.Offset})";
            if (v.Kind == CSymbolKind.Global)
                return $"({v.Label})";
            return null;
        }

        private bool TryLoadVarDirect(CSymbol v, CType ty)
        {
            string op = DirectOperand(v);
            if (op == null || !ty.IsScalar)
                return false;

            switch (ty.Size)
            {
                case 4:
                    Emit($"LD ABCD, {op}");
                    return true;
                case 2:
                    Emit("LD ABCD, 0");
                    Emit($"LD CD, {op}");
                    SignExtend(ty);
                    return true;
                case 1:
                    Emit("LD ABCD, 0");
                    Emit($"LD D, {op}");
                    SignExtend(ty);
                    return true;
            }
            return false;
        }

        private void StoreDirect(CSymbol v, CType ty)
        {
            string op = DirectOperand(v);
            switch (ty.Size)
            {
                case 4: Emit($"LD {op}, ABCD"); return;
                case 2: Emit($"LD {op}, CD"); return;
                case 1: Emit($"LD {op}, D"); return;
            }
            throw new InvalidOperationException("Unexpected scalar size");
        }

        /// <summary>Loads a value of the given type from the address in ABCD into ABCD.</summary>
        private void Load(CType ty)
        {
            if (ty.IsArray || ty.IsStruct || ty.IsFunction)
                return; // The address is the value

            switch (ty.Size)
            {
                case 4:
                    Emit("LD ABCD, (BCD)");
                    return;
                case 2:
                    Emit("LD MNO, BCD");
                    Emit("LD ABCD, 0");
                    Emit("LD CD, (MNO)");
                    SignExtend(ty);
                    return;
                case 1:
                    Emit("LD MNO, BCD");
                    Emit("LD ABCD, 0");
                    Emit("LD D, (MNO)");
                    SignExtend(ty);
                    return;
            }
        }

        /// <summary>Stores ABCD to the address in MNO.</summary>
        private void Store(CType ty)
        {
            switch (ty.Size)
            {
                case 4: Emit("LD (MNO), ABCD"); return;
                case 2: Emit("LD (MNO), CD"); return;
                case 1: Emit("LD (MNO), D"); return;
            }
            throw new InvalidOperationException($"Cannot store type {ty}");
        }

        /// <summary>Sign-extends the low 8/16 bits of ABCD (already zero-extended) for signed types.</summary>
        private void SignExtend(CType ty)
        {
            if (ty.Unsigned || ty.Size == 4)
                return;
            uint bit = ty.Size == 1 ? 0x80u : 0x8000u;
            Emit($"XOR ABCD, 0x{bit:X}");
            Emit($"SUB32 ABCD, 0x{bit:X}");
        }

        /// <summary>Converts the value in ABCD from one type to another (truncation and sign/zero extension).</summary>
        private void Convert(CType from, CType to)
        {
            if (to.IsVoid)
                return;

            if (to.IsBool)
            {
                if (from.IsBool) return;
                string done = NewLabel();
                Emit("CP ABCD, 0");
                Emit("LD ABCD, 0");
                Emit($"JP Z, {done}");
                Emit("LD ABCD, 1");
                Label(done);
                return;
            }

            int fs = from.IsScalar ? from.Size : 4;
            int ts = to.Size;
            if (ts >= 4) return;
            if (ts > fs && from.Unsigned) return;
            if (ts == fs && to.Unsigned == from.Unsigned) return;

            Emit($"AND ABCD, 0x{(ts == 1 ? 0xFF : 0xFFFF):X}");
            SignExtend(to);
        }

        // ====================================================================== Emission helpers

        private void AddImm32(string reg, long value)
        {
            int v = (int)value;
            if (v > 0) Emit($"ADD32 {reg}, {v}");
            else if (v < 0) Emit($"SUB32 {reg}, {-(long)v}");
        }

        private static string Imm(long value) => $"0x{(uint)value:X}";

        private static bool IsPowerOfTwo(long v, out int shift)
        {
            shift = 0;
            uint u = (uint)v;
            if (u == 0 || (u & (u - 1)) != 0) return false;
            while ((1u << shift) != u) shift++;
            return true;
        }

        private void EmitBytes(byte[] bytes)
        {
            for (int i = 0; i < bytes.Length; i += 32)
            {
                int n = Math.Min(32, bytes.Length - i);
                Emit("#DB " + string.Join(", ", bytes.Skip(i).Take(n).Select(b => $"0x{b:X2}")));
            }
        }

        private string NewLabel() => $".c__L{_labelCounter++}";

        private void Emit(string s) => _sb.Append("    ").Append(s).Append('\n');

        private void Label(string s) => _sb.Append(s).Append('\n');

        private void Line(string s) => _sb.Append(s).Append('\n');

        private CCompileAbort Internal(CNode node, string message)
        {
            var t = node.Tok;
            _errors.Add(new CCompileError(t?.File ?? "?", t?.Line ?? 0, t?.Column ?? 0, "Internal compiler error: " + message));
            return new CCompileAbort();
        }
    }
